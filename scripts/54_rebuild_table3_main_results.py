#!/usr/bin/env python
from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
STATS_CSV = ROOT / "reports" / "v31_split_protocol_main" / "v31_s2_main_stats.csv"
CONDITION_STATS_CSV = ROOT / "reports" / "v31_split_protocol_main" / "v31_s2_condition_stats.csv"
OUT_TEX = ROOT / "paper" / "tables" / "main_results_v31.tex"
OUT_CONDITION_TEX = ROOT / "paper" / "tables" / "condition_results_v31.tex"

METRIC_MEAN = "forecast_weighted_mae_overall_mean"
METRIC_STD = "forecast_weighted_mae_overall_std"
METRIC_COUNT = "forecast_weighted_mae_overall_count"

BUDGETS = [1.65, 1.70, 1.75]
POLICIES = [
    ("full_open_unconstrained", "Full observation (unconstrained)", False),
    ("validation_selected_static", "Validation-selected static", False),
    ("custom_ppo", "PD-PPO (ours)", False),
    ("round_robin", "Round-robin", False),
    ("aoi", "AoI-based", False),
    ("random", "Random feasible", False),
]
CONDITION_POLICIES = [
    ("full_open_unconstrained", "Full obs."),
    ("validation_selected_static", "Val.-selected static"),
    ("custom_ppo", "PD-PPO"),
    ("round_robin", "Round-robin"),
    ("aoi", "AoI"),
    ("random", "Random"),
]
CONDITIONS = [("non_event", "Non-event"), ("event", "Event")]


def budget_label(value: float) -> str:
    return f"$B = {value:.2f}$"


def value_cell(mean: float, std: float, *, bold: bool) -> str:
    value = f"{mean:.4f} \\pm {std:.4f}"
    if bold:
        return f"$\\mathbf{{{value}}}$"
    return f"${value}$"


def load_table() -> pd.DataFrame:
    if not STATS_CSV.exists():
        raise FileNotFoundError(f"Missing source CSV: {STATS_CSV}")
    stats = pd.read_csv(STATS_CSV)
    required = {"budget", "policy", METRIC_MEAN, METRIC_STD, METRIC_COUNT}
    missing = sorted(required.difference(stats.columns))
    if missing:
        raise ValueError(f"{STATS_CSV} is missing columns: {missing}")
    return stats


def load_condition_table() -> pd.DataFrame:
    if not CONDITION_STATS_CSV.exists():
        raise FileNotFoundError(f"Missing source CSV: {CONDITION_STATS_CSV}")
    stats = pd.read_csv(CONDITION_STATS_CSV)
    required = {"budget", "condition", "policy", "mean", "std", "count"}
    missing = sorted(required.difference(stats.columns))
    if missing:
        raise ValueError(f"{CONDITION_STATS_CSV} is missing columns: {missing}")
    return stats


def build_latex(stats: pd.DataFrame) -> str:
    lines: list[str] = [
        "% Auto-generated by scripts/54_rebuild_table3_main_results.py from",
        f"% {STATS_CSV.relative_to(ROOT)}",
        r"\begin{table}[htbp]",
        r"  \centering",
        r"  \caption{Chronological split-protocol fixed-budget forecast-weighted MAE across power budgets.",
        r"  Lower values indicate better downstream forecast quality. Entries are",
        r"  mean $\pm$ standard deviation across $n=10$ random seeds, regenerated from",
        r"  final-test outputs with disjoint oracle-pretrain, RL-train, validation,",
        r"  and test partitions. Full observation is an unconstrained diagnostic",
        r"  reference; the static comparator is selected on validation windows only.}",
        r"  \label{tab:main_results}",
        r"  \resizebox{\linewidth}{!}{%",
        r"  \begin{tabular}{@{}lccc@{}}",
        r"    \toprule",
        "    Policy & " + " & ".join(budget_label(budget) for budget in BUDGETS) + r" \\",
        r"    \midrule",
    ]

    for policy, label, bold in POLICIES:
        row = [f"    {label}"]
        for budget in BUDGETS:
            match = stats[(stats["policy"] == policy) & (stats["budget"].round(2) == round(budget, 2))]
            if match.empty:
                raise ValueError(f"Missing row for policy={policy!r}, budget={budget:.2f}")
            if int(match.iloc[0][METRIC_COUNT]) != 10:
                raise ValueError(
                    f"Unexpected seed count for policy={policy!r}, budget={budget:.2f}: "
                    f"{match.iloc[0][METRIC_COUNT]}"
                )
            row.append(
                value_cell(
                    float(match.iloc[0][METRIC_MEAN]),
                    float(match.iloc[0][METRIC_STD]),
                    bold=bold,
                )
            )
        lines.append(row[0])
        lines.append("      & " + " & ".join(row[1:]) + r" \\")

    lines.extend(
        [
            r"    \bottomrule",
            r"  \end{tabular}%",
            r"  }",
            r"\end{table}",
            "",
        ]
    )
    return "\n".join(lines)


def build_condition_latex(stats: pd.DataFrame, *, budget: float = 1.70) -> str:
    lines: list[str] = [
        "% Auto-generated by scripts/54_rebuild_table3_main_results.py from",
        f"% {CONDITION_STATS_CSV.relative_to(ROOT)}",
        r"\begin{table}[htbp]",
        r"  \centering",
        rf"  \caption{{Final-test FW-MAE stratified by simulator event state at $B={budget:.2f}$",
        r"  under the chronological split protocol. Entries are mean $\pm$ standard",
        r"  deviation across $n=10$ matched seeds; the static comparator was selected",
        r"  using validation windows only. Event labels define these strata and are",
        r"  available as simulated context to PD-PPO; deployment would require",
        r"  inference of that context from available measurements.}",
        r"  \label{tab:e1_condition}",
        r"  \scriptsize",
        r"  \resizebox{\linewidth}{!}{%",
        r"  \begin{tabular}{@{}lcccccc@{}}",
        r"    \toprule",
        "    Condition & " + " & ".join(label for _, label in CONDITION_POLICIES) + r" \\",
        r"    \midrule",
    ]
    for condition, label in CONDITIONS:
        cells: list[str] = []
        for policy, _ in CONDITION_POLICIES:
            match = stats[
                (stats["condition"] == condition)
                & (stats["policy"] == policy)
                & (stats["budget"].round(2) == round(budget, 2))
            ]
            if match.empty:
                raise ValueError(
                    f"Missing condition row for policy={policy!r}, condition={condition!r}, budget={budget:.2f}"
                )
            if int(match.iloc[0]["count"]) != 10:
                raise ValueError(
                    f"Unexpected seed count for policy={policy!r}, condition={condition!r}: "
                    f"{match.iloc[0]['count']}"
                )
            cells.append(value_cell(float(match.iloc[0]["mean"]), float(match.iloc[0]["std"]), bold=False))
        lines.append(f"    {label}")
        lines.append("      & " + " & ".join(cells) + r" \\")
    lines.extend([r"    \bottomrule", r"  \end{tabular}%", r"  }", r"\end{table}", ""])
    return "\n".join(lines)


def main() -> None:
    stats = load_table()
    condition_stats = load_condition_table()
    OUT_TEX.write_text(build_latex(stats), encoding="utf-8")
    OUT_CONDITION_TEX.write_text(build_condition_latex(condition_stats), encoding="utf-8")
    print(OUT_TEX)
    print(OUT_CONDITION_TEX)


if __name__ == "__main__":
    main()
